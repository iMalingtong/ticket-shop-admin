package com.ticketshop.admin.common.api;

public enum ErrorCode {
    VALIDATION_ERROR(400),
    PROTOCOL_INVALID(400),
    INVALID_CREDENTIALS(401),
    SESSION_INVALID(401),
    SESSION_EXPIRED(401),
    SESSION_REVOKED(401),
    PASSWORD_CHANGE_TOKEN_INVALID(401),
    ACCOUNT_FROZEN(403),
    ACCOUNT_DISABLED(403),
    ACCOUNT_NOT_STARTED(403),
    ACCOUNT_EXPIRED(403),
    PASSWORD_CHANGE_REQUIRED(403),
    FORBIDDEN(403),
    CSRF_INVALID(403),
    RESOURCE_NOT_FOUND(404),
    VERSION_CONFLICT(409),
    USERNAME_EXISTS(409),
    INVALID_STATE_TRANSITION(409),
    LAST_SUPER_ADMIN(409),
    IDEMPOTENCY_CONFLICT(409),
    CLIENT_UPDATE_REQUIRED(426),
    PROTOCOL_UNSUPPORTED(426),
    LOGIN_RATE_LIMITED(429),
    SERVICE_UNAVAILABLE(503),
    MAINTENANCE(503);
    private final int httpStatus;
    ErrorCode(int value) { httpStatus = value; }
    public int httpStatus() { return httpStatus; }
}
